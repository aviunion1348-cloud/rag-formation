"""Automated checks for docs/lear_backend (``lear docs verify``).

Checks (each PASS / WARN / FAIL with examples):

* ``pin``            – SOURCE_PIN.json exists, names a commit, and the source
                       checkout (when supplied) is at that commit;
* ``required_pages`` – the core pages exist and are not empty placeholders;
* ``links``          – relative markdown links resolve inside the docs tree;
* ``source_refs``    – every ``path:Lx-Ly`` exists at the pinned commit
                       (read with ``git show <commit>:<path>``) and the range
                       is inside the file;
* ``stale_commits``  – no other 7–40 hex commit id is presented as the pin;
* ``claim_labels``   – narrative claim bullets carry evidence and one of the
                       labels implemented / configured / tested / inferred;
* ``duplicates``     – identical long paragraphs across pages and identical
                       chunks after real chunking;
* ``secrets``        – credential patterns (and full-length hex ids outside
                       SOURCE_PIN.json);
* ``guardrails``     – chunks produced by the real loader + chunker that the
                       engine's prompt-injection guard would quarantine;
* ``api_auth_claim`` – re-derives, from the AST of ``prash/server.py`` at the
                       pinned commit, the documented claim that no route
                       declares an authentication dependency.

``coverage`` measures how much of the source the docs reference.
"""

from __future__ import annotations

import ast
import json
import re
import subprocess
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

from ..chunking import Chunker
from ..guardrails import _CREDENTIAL_PATTERNS, scan_text
from ..loaders import load_bytes
from .indexer import prepare_for_index
from .settings import LearSettings

REQUIRED_PAGES = (
    "README.md",
    "architecture.md",
    "api_reference.md",
    "domain_model.md",
    "database.md",
    "authentication_authorization.md",
    "services_and_workflows.md",
    "configuration.md",
    "integrations.md",
    "errors_and_operations.md",
    "testing.md",
    "source_map.md",
    "unknowns_and_gaps.md",
)
LABELS = ("implemented", "configured", "tested", "inferred")
REF = re.compile(r"`?([A-Za-z0-9_./-]+\.[A-Za-z0-9]+):L(\d+)(?:-L?(\d+))?`?")
LINK = re.compile(r"(?<!!)\[([^\]]+)\]\(([^)\s]+)\)")
HEX = re.compile(r"\b[0-9a-f]{7,40}\b")
EMAIL = re.compile(r"\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b")
ROUTE_METHODS = {"get", "post", "put", "delete", "patch", "websocket", "api_route", "head", "options"}
LABEL_TAG = re.compile(r"\*\*\[(implemented|configured|tested|inferred)\]\*\*", re.IGNORECASE)
GENERATED_MARK = "Generated by `python -m ragformation lear docs build`"


def _check(name: str, status: str, summary: str, examples: Optional[List[Any]] = None, **extra: Any) -> Dict[str, Any]:
    return {"name": name, "status": status, "summary": summary, "examples": (examples or [])[:12], **extra}


class _SourceReader:
    def __init__(self, source: Optional[Path], commit: Optional[str]) -> None:
        self.source = source
        self.commit = commit
        self._lines: Dict[str, Optional[int]] = {}

    def line_count(self, rel: str) -> Optional[int]:
        if rel in self._lines:
            return self._lines[rel]
        count: Optional[int] = None
        if self.source is not None and self.commit:
            proc = subprocess.run(
                ["git", "-C", str(self.source), "show", f"{self.commit}:{rel}"],
                capture_output=True,
                timeout=30,
            )
            if proc.returncode == 0:
                data = proc.stdout
                count = data.count(b"\n") + (1 if data and not data.endswith(b"\n") else 0)
        self._lines[rel] = count
        return count


def _pages(docs_dir: Path) -> List[Path]:
    return sorted(p for p in docs_dir.rglob("*.md") if p.is_file())


def _is_generated(text: str) -> bool:
    return GENERATED_MARK in text[:600]


def verify_docs(docs_dir: Path, source: Optional[Path] = None) -> Dict[str, Any]:
    docs_dir = Path(docs_dir)
    checks: List[Dict[str, Any]] = []
    pin_path = docs_dir / "SOURCE_PIN.json"
    pin: Dict[str, Any] = {}
    if pin_path.exists():
        try:
            pin = json.loads(pin_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            checks.append(_check("pin", "FAIL", f"SOURCE_PIN.json is not valid JSON: {exc}"))
    commit = pin.get("commit")
    short = (commit or "")[:12]
    source_head = None
    source = Path(source).expanduser() if source else None
    if source is not None and (source / ".git").exists():
        proc = subprocess.run(["git", "-C", str(source), "rev-parse", "HEAD"], capture_output=True, text=True, timeout=30)
        source_head = proc.stdout.strip() if proc.returncode == 0 else None
    else:
        source = None
    if not commit:
        checks.append(_check("pin", "FAIL", "SOURCE_PIN.json missing or has no commit"))
    elif source is None:
        checks.append(_check("pin", "WARN", f"pinned {short}; source checkout not supplied, so path:line references cannot be verified"))
    elif source_head != commit:
        checks.append(_check("pin", "WARN", f"pinned {short} but checkout HEAD is {str(source_head)[:12]}; references are verified against the pinned commit via git show"))
    else:
        checks.append(_check("pin", "PASS", f"pinned {pin.get('repository')} @ {short}; checkout HEAD matches"))

    pages = _pages(docs_dir)
    texts = {p: p.read_text(encoding="utf-8") for p in pages}
    rel_names = {p.relative_to(docs_dir).as_posix() for p in pages}

    # required pages -------------------------------------------------------
    missing = [name for name in REQUIRED_PAGES if name not in rel_names]
    thin = [name for name in REQUIRED_PAGES if name in rel_names and len(texts[docs_dir / name].split()) < 120]
    status = "FAIL" if missing or thin else "PASS"
    checks.append(_check("required_pages", status, f"{len(REQUIRED_PAGES) - len(missing)}/{len(REQUIRED_PAGES)} present; {len(thin)} below 120 words", missing + [f"thin: {t}" for t in thin]))

    # links -----------------------------------------------------------------
    broken = []
    link_count = 0
    for page, text in texts.items():
        for _, target in LINK.findall(text):
            if re.match(r"^[a-z]+://", target) or target.startswith("#") or target.startswith("mailto:"):
                continue
            link_count += 1
            path_part = target.split("#", 1)[0]
            resolved = (page.parent / path_part).resolve()
            if not resolved.exists():
                broken.append(f"{page.relative_to(docs_dir)} -> {target}")
    checks.append(_check("links", "FAIL" if broken else "PASS", f"{link_count} relative links, {len(broken)} broken", broken))

    # source references -------------------------------------------------------
    reader = _SourceReader(source, commit)
    ref_total = 0
    bad_refs = []
    refs_by_file: Dict[str, int] = defaultdict(int)
    referenced_paths: Dict[str, set] = defaultdict(set)
    for page, text in texts.items():
        narrative = not _is_generated(text)
        for path, start, end in REF.findall(text):
            ref_total += 1
            refs_by_file[path] += 1
            referenced_paths["narrative" if narrative else "generated"].add(path)
            if source is None:
                continue
            count = reader.line_count(path)
            s, e = int(start), int(end or start)
            if count is None:
                bad_refs.append(f"{page.relative_to(docs_dir)}: {path} not found at {short}")
            elif not (1 <= s <= e <= count):
                bad_refs.append(f"{page.relative_to(docs_dir)}: {path}:L{s}-L{e} outside 1..{count}")
    if source is None:
        checks.append(_check("source_refs", "WARN", f"{ref_total} references found; not verified (no source)"))
    else:
        checks.append(_check("source_refs", "FAIL" if bad_refs else "PASS", f"{ref_total} references, {len(bad_refs)} invalid", bad_refs))

    # stale commit ids --------------------------------------------------------
    stale = []
    for page, text in texts.items():
        for match in re.finditer(r"(?:commit|@)\s*`?([0-9a-f]{7,40})`?", text):
            value = match.group(1)
            if commit and not commit.startswith(value):
                stale.append(f"{page.relative_to(docs_dir)}: {value}")
    narrative_pages = [p for p in pages if not _is_generated(texts[p])]
    unpinned = [p.relative_to(docs_dir).as_posix() for p in narrative_pages if short and short not in texts[p]]
    status = "FAIL" if stale else ("WARN" if unpinned else "PASS")
    checks.append(_check("stale_commits", status, f"{len(stale)} foreign commit ids; {len(unpinned)} narrative pages without the pinned id", stale + [f"no pin: {u}" for u in unpinned]))

    # claim labels -------------------------------------------------------------
    claim_lines = 0
    labelled = 0
    with_ref = 0
    label_counts: Dict[str, int] = defaultdict(int)
    unlabelled = []
    for page in narrative_pages:
        for number, line in enumerate(texts[page].splitlines(), 1):
            stripped = line.strip()
            if not (stripped.startswith("- ") or stripped.startswith("| ")):
                continue
            tag = LABEL_TAG.search(stripped)
            has_ref = bool(REF.search(stripped))
            if not tag and not has_ref:
                continue
            claim_lines += 1
            if tag:
                labelled += 1
                label_counts[tag.group(1).lower()] += 1
            if has_ref or (tag and tag.group(1).lower() == "inferred"):
                with_ref += 1
            if not tag or not (has_ref or tag.group(1).lower() == "inferred"):
                unlabelled.append(f"{page.relative_to(docs_dir)}:{number}")
    status = "PASS" if claim_lines and not unlabelled else ("FAIL" if unlabelled else "WARN")
    checks.append(_check(
        "claim_labels",
        status,
        f"{claim_lines} claim lines; {labelled} labelled; {with_ref} with evidence (inferred claims may cite none)",
        unlabelled,
        labels=dict(label_counts),
    ))

    # duplicates --------------------------------------------------------------
    paragraphs: Dict[str, List[str]] = defaultdict(list)
    for page in narrative_pages:
        for para in re.split(r"\n\s*\n", texts[page]):
            norm = " ".join(para.split()).lower()
            if len(norm) >= 160 and not norm.startswith("|") and not norm.startswith(">"):
                paragraphs[norm].append(page.relative_to(docs_dir).as_posix())
    dups = [f"{pages_[0]} and {pages_[1]}: {para[:70]}…" for para, pages_ in paragraphs.items() if len(set(pages_)) > 1]
    settings = LearSettings(docs_dir=docs_dir).engine_settings()
    chunker = Chunker(settings)
    chunk_hashes: Dict[str, List[str]] = defaultdict(list)
    quarantined = []
    chunk_total = 0
    for page, text in texts.items():
        indexed = prepare_for_index(text)  # same markers the indexer applies
        if indexed is None:
            continue
        loaded = load_bytes(page.name, indexed.encode("utf-8"), max_bytes=settings.max_source_bytes)
        for chunk in chunker.chunk(loaded, "verify-" + page.stem):
            chunk_total += 1
            chunk_hashes[chunk.content_hash].append(f"{page.relative_to(docs_dir)}#{chunk.ordinal}")
            findings = scan_text(chunk.text)
            if findings:
                quarantined.append(f"{page.relative_to(docs_dir)}#{chunk.ordinal}: {findings[0].rule_id}: {findings[0].excerpt[:90]}")
    dup_chunks = [", ".join(v) for v in chunk_hashes.values() if len(v) > 1]
    status = "WARN" if dups or dup_chunks else "PASS"
    checks.append(_check("duplicates", status, f"{len(dups)} repeated paragraphs; {len(dup_chunks)} identical chunks of {chunk_total}", dups + dup_chunks))
    checks.append(_check("guardrails", "FAIL" if quarantined else "PASS", f"{len(quarantined)} of {chunk_total} chunks would be quarantined by the injection guard", quarantined))

    # secrets -------------------------------------------------------------------
    secret_hits = []
    for page, text in texts.items():
        for rule, pattern in _CREDENTIAL_PATTERNS:
            for match in pattern.finditer(text):
                secret_hits.append(f"{page.relative_to(docs_dir)}: {rule}: {match.group(0)[:12]}…")
        for match in EMAIL.finditer(text):
            address = match.group(0).lower()
            if "noreply" in address or address.endswith("@example.com"):
                continue
            secret_hits.append(f"{page.relative_to(docs_dir)}: email_address: {address.split('@')[0][:3]}…@…")
    checks.append(_check("secrets", "FAIL" if secret_hits else "PASS", f"{len(secret_hits)} credential-pattern or personal email hits in markdown (SOURCE_PIN.json may hold the full commit id)", secret_hits))

    if source is not None and commit:
        auth = check_api_auth(source, commit)
        checks.append(auth)
        http_page = docs_dir / "reference" / "http_api.md"
        documented = re.search(r"Routes found: (\d+)", texts.get(http_page, ""))
        if documented and auth.get("routes") is not None:
            same = int(documented.group(1)) == auth["routes"]
            checks.append(_check(
                "route_count",
                "PASS" if same else "FAIL",
                f"reference/http_api.md documents {documented.group(1)} routes; the AST of prash/server.py has {auth['routes']}",
            ))

    coverage = measure_coverage(source, commit, referenced_paths) if source is not None else None
    passed = all(c["status"] != "FAIL" for c in checks)
    return {
        "passed": passed,
        "docsDir": str(docs_dir),
        "pin": {k: pin.get(k) for k in ("repository", "commit", "branch", "commit_date")},
        "pages": len(pages),
        "narrativePages": len(narrative_pages),
        "generatedPages": len(pages) - len(narrative_pages),
        "checks": checks,
        "coverage": coverage,
        "refsByFile": dict(sorted(refs_by_file.items(), key=lambda kv: -kv[1])[:30]),
    }


def _call_name(node: ast.AST) -> str:
    if isinstance(node, ast.Call):
        node = node.func
    if isinstance(node, ast.Attribute):
        return node.attr
    if isinstance(node, ast.Name):
        return node.id
    return ""


def check_api_auth(source: Path, commit: str, rel: str = "prash/server.py") -> Dict[str, Any]:
    """Recompute the "no route declares an authentication dependency" claim."""
    proc = subprocess.run(["git", "-C", str(source), "show", f"{commit}:{rel}"], capture_output=True, text=True, timeout=30)
    if proc.returncode != 0:
        return _check("api_auth_claim", "WARN", f"{rel} not found at {commit[:12]}; claim not checked")
    tree = ast.parse(proc.stdout)
    routes = 0
    decorators = 0
    with_auth: List[str] = []
    middleware: List[str] = []
    custom_middleware: List[str] = []
    app_level: List[str] = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            for deco in node.decorator_list:
                if not (isinstance(deco, ast.Call) and isinstance(deco.func, ast.Attribute)):
                    continue
                if deco.func.attr == "middleware":
                    custom_middleware.append(f"{node.name} L{node.lineno}")
                    continue
                if deco.func.attr not in ROUTE_METHODS:
                    continue
                decorators += 1
                if deco.func.attr == "api_route":
                    declared = next((kw.value for kw in deco.keywords if kw.arg == "methods"), None)
                    routes += len(getattr(declared, "elts", [])) or 1
                else:
                    routes += 1
                reasons = [kw.arg for kw in deco.keywords if kw.arg == "dependencies"]
                defaults = list(node.args.defaults) + [d for d in node.args.kw_defaults if d is not None]
                reasons += [_call_name(d) for d in defaults if _call_name(d) in {"Depends", "Security"}]
                for arg in node.args.args + node.args.kwonlyargs:
                    if arg.annotation is not None and any(_call_name(n) in {"Depends", "Security"} for n in ast.walk(arg.annotation) if isinstance(n, ast.Call)):
                        reasons.append("Annotated dependency")
                if reasons:
                    with_auth.append(f"{node.name} L{node.lineno}: {', '.join(sorted(set(r or '' for r in reasons)))}")
        elif isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "add_middleware" and node.args:
            middleware.append(_call_name(node.args[0]))
        elif isinstance(node, ast.Call) and _call_name(node) == "FastAPI":
            app_level += [kw.arg for kw in node.keywords if kw.arg == "dependencies"]
    non_cors = [m for m in middleware if m != "CORSMiddleware"]
    holds = not with_auth and not custom_middleware and not app_level and not non_cors
    summary = (
        f"{routes} method/path routes from {decorators} route decorators in {rel}; {len(with_auth)} declare Depends/Security/dependencies; "
        f"middleware: {', '.join(middleware) or 'none'}; custom @app.middleware: {len(custom_middleware)}; "
        + ("documented 'no authentication dependency' claim holds" if holds else "documented claim is CONTRADICTED")
    )
    return _check("api_auth_claim", "PASS" if holds else "FAIL", summary, with_auth + custom_middleware + non_cors + app_level, routes=routes)


def measure_coverage(source: Optional[Path], commit: Optional[str], referenced: Dict[str, set]) -> Dict[str, Any]:
    if source is None or not commit:
        return {}
    proc = subprocess.run(["git", "-C", str(source), "ls-tree", "-r", "--name-only", commit], capture_output=True, text=True, timeout=60)
    files = [f for f in proc.stdout.splitlines() if f]
    modules = [f for f in files if f.startswith("prash/") and f.endswith(".py") and not f.endswith("__init__.py")]
    narrative = referenced.get("narrative", set())
    generated = referenced.get("generated", set())
    in_narrative = [m for m in modules if m in narrative]
    in_any = [m for m in modules if m in narrative or m in generated]
    tests = [f for f in files if f.startswith("tests/") and f.endswith(".py")]
    return {
        "modules": len(modules),
        "modulesWithNarrativeEvidence": len(in_narrative),
        "modulesWithAnyEvidence": len(in_any),
        "narrativeCoverage": round(len(in_narrative) / len(modules), 3) if modules else 0.0,
        "anyCoverage": round(len(in_any) / len(modules), 3) if modules else 0.0,
        "modulesWithoutNarrative": sorted(set(modules) - set(in_narrative)),
        "testFiles": len(tests),
        "testFilesReferenced": len([t for t in tests if t in narrative or t in generated]),
    }


def render_verify(report: Dict[str, Any]) -> str:
    lines = [f"Lear docs verify — {report['docsDir']} pages={report['pages']} (narrative {report['narrativePages']}, generated {report['generatedPages']})"]
    pin = report["pin"]
    lines.append(f"pin: {pin.get('repository')} @ {(pin.get('commit') or '')[:12]} ({pin.get('commit_date')})")
    for check in report["checks"]:
        lines.append(f"  [{check['status']:4}] {check['name']}: {check['summary']}")
        for example in check["examples"][:5]:
            lines.append(f"         - {example}")
    cov = report.get("coverage") or {}
    if cov:
        lines.append(
            f"coverage: {cov['modulesWithNarrativeEvidence']}/{cov['modules']} modules cited by narrative pages "
            f"({cov['narrativeCoverage']:.0%}); {cov['modulesWithAnyEvidence']}/{cov['modules']} cited anywhere ({cov['anyCoverage']:.0%})"
        )
    lines.append("RESULT: " + ("PASS" if report["passed"] else "FAIL"))
    return "\n".join(lines)


def render_coverage(report: Dict[str, Any]) -> str:
    cov = report.get("coverage") or {}
    pin = report["pin"]
    out = [
        "# Documentation coverage — docs/lear_backend",
        "",
        f"Produced by `python -m ragformation lear docs verify --source <lear checkout> --write-coverage` against "
        f"`{pin.get('repository')}` at commit `{(pin.get('commit') or '')[:12]}`. Re-run it after any docs change; "
        "this file is overwritten by that command.",
        "",
        "## Verification checks",
        "",
        "| Check | Status | Result |",
        "|---|---|---|",
    ]
    for check in report["checks"]:
        out.append(f"| {check['name']} | {check['status']} | {check['summary']} |")
    out += ["", f"Overall: **{'PASS' if report['passed'] else 'FAIL'}**.", ""]
    labels = next((c.get("labels") for c in report["checks"] if c["name"] == "claim_labels"), {}) or {}
    if labels:
        out += ["## Evidence labels on narrative claims", "", "| Label | Claims |", "|---|---:|"]
        for label in LABELS:
            out.append(f"| {label} | {labels.get(label, 0)} |")
        out.append("")
    if cov:
        out += [
            "## Source coverage",
            "",
            f"- Python modules in `prash/` (excluding `__init__.py`): {cov['modules']}.",
            f"- Cited by at least one narrative page: {cov['modulesWithNarrativeEvidence']} ({cov['narrativeCoverage']:.0%}).",
            f"- Cited anywhere, including the generated reference pages: {cov['modulesWithAnyEvidence']} ({cov['anyCoverage']:.0%}).",
            f"- Test files referenced: {cov['testFilesReferenced']} of {cov['testFiles']}.",
            "",
            "Modules with no narrative citation are still listed, with line spans, in `reference/modules.md`:",
            "",
        ]
        out.append(", ".join(f"`{m}`" for m in cov["modulesWithoutNarrative"]) or "none")
        out.append("")
    out += ["## Most-cited files", "", "| File | References |", "|---|---:|"]
    for path, count in report.get("refsByFile", {}).items():
        out.append(f"| `{path}` | {count} |")
    out.append("")
    return "\n".join(out)
