"""Generate docs/lear_agent/demo_effects.md from the effect registry.

The page is generated: edit ``ragformation/lear/demo_effects.py`` and rerun
``python3 scripts/gen_demo_effects_doc.py``. ``tests/test_lear_demo.py``
fails if the page and the registry disagree.
"""

from __future__ import annotations

import collections
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from ragformation.lear import demo_effects as fx  # noqa: E402

OUT = REPO / "docs" / "lear_agent" / "demo_effects.md"


def wired_ids() -> set:
    src = (REPO / "ragformation" / "lear" / "demo.py").read_text(encoding="utf-8")
    calls = re.findall(r'(?:self\.fx|fx\.play)\((?:[a-z_]+, )?"([a-z0-9_]+)"', src)
    return {m for m in calls if m in fx.BY_ID}


def esc(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def main() -> int:
    rows = [r.to_dict() for r in fx.RECIPES]
    wired = wired_ids()
    shared = {k: rows[0][k] for k in ("interrupt", "noColour", "cleanup", "seed", "test")
              if len({r[k] for r in rows}) == 1}
    fams = collections.OrderedDict()
    for r in rows:
        fams.setdefault(r["family"], []).append(r)
    out = []
    w = out.append
    w("# `lear demo` effect registry")
    w("")
    w(f"<!-- generated by scripts/gen_demo_effects_doc.py from {fx.REGISTRY_VERSION}; do not edit by hand -->")
    w("")
    w(f"Registry **`{fx.REGISTRY_VERSION}`**: **{len(rows)} recipes** in **{len(fams)} families**, built from "
      f"**{len(fx.LAYOUTS)} layouts** (what is drawn) and **{len(fx.MOTIONS)} motions** (how it arrives). "
      f"**{len(wired)}** recipes are wired into scenes S00-S11; the other {len(rows) - len(wired)} are available to "
      "`lear demo effects --preview <id>` and to future scenes, and are drawn from labelled example data there.")
    w("")
    w("Source: [`ragformation/lear/demo_effects.py`](../../ragformation/lear/demo_effects.py). "
      "List: `python3 -m ragformation lear demo effects` (`--json` for the full record of every field). "
      "Preview: `python3 -m ragformation lear demo effects --preview <id>[,<id>...]` or `--preview all` "
      "([`evidence/demo/effects_preview_plain.txt`](evidence/demo/effects_preview_plain.txt)).")
    w("")
    w("## What counts as a recipe")
    w("")
    w("- A recipe is **one real event drawn one way**: a unique `purpose` (the real value it shows) and a unique "
      "`(layout, motion, purpose)` triple. Colour-only or speed-only variants do not count, and the registry test "
      "fails on a duplicate id, purpose or triple (`EffectRegistryTests`).")
    w("- **The static form is the final frame.** With motion off (`--plain`, `--no-animate`, `--speed 0`, non-TTY, "
      "`CI`, `NO_COLOR`, `TERM=dumb`) every recipe prints exactly the lines its animation ends on. "
      "`test_static_form_is_the_final_frame_of_the_animated_form` checks this for all recipes, and bounds the frame count.")
    w("- **No invented values.** A recipe draws only the data it is handed. Typing is reserved for a real model "
      "stream (`answer_stream` with `realStream`); extractive baseline output prints at once "
      "(`test_typing_is_reserved_for_a_real_model_stream`).")
    w("- **Correction to the previous version.** The v1 guide claimed 36 effects; the code had 20 distinct motion "
      "methods. This registry replaces it; see [demo_production_audit.md](demo_production_audit.md).")
    w("")
    w("## Contract shared by every recipe")
    w("")
    w("| Field | Value |")
    w("|---|---|")
    for k, v in shared.items():
        w(f"| {k} | {esc(v)} |")
    w("| terminal | " + esc(" / ".join(sorted({r['terminal'] for r in rows}))) + " |")
    w("")
    w("## Layouts (what is drawn)")
    w("")
    w("| Layout | Static / reduced-motion form | Recipes |")
    w("|---|---|---|")
    by_layout = collections.Counter(r["layout"] for r in rows)
    reduced = {r["layout"]: r["reduced"] for r in rows}
    for name in sorted(fx.LAYOUTS):
        w(f"| `{name}` | {esc(reduced.get(name, 'static lines'))} | {by_layout.get(name, 0)} |")
    w("")
    w("## Motions (how it arrives)")
    w("")
    w("| Motion | Timing at `--speed 1` | Mechanism | Recipes |")
    w("|---|---|---|---|")
    by_motion = collections.Counter(r["motion"] for r in rows)
    timing = {r["motion"]: (r["timing"], r["mechanism"]) for r in rows}
    for name in sorted(fx.MOTIONS):
        t, m = timing.get(name, ("-", "-"))
        w(f"| `{name}` | {esc(t)} | {esc(m)} | {by_motion.get(name, 0)} |")
    w("")
    w("## Recipes by family")
    w("")
    w("Columns: **id** (stable, used by `--preview`), **draw** (layout x motion), **scene**, **trigger**, "
      "**real event shown**, **cost**, **wired** (used by a scene today), **accessibility** note.")
    for fam, items in fams.items():
        w("")
        w(f"### {fam} ({len(items)})")
        w("")
        w("| id | draw | scene | trigger | real event shown | cost | wired | accessibility |")
        w("|---|---|---|---|---|---|---|---|")
        for r in items:
            w(f"| `{r['id']}` | {r['layout']} x {r['motion']} | {esc(r['scene'])} | {esc(r['trigger'])} | "
              f"{esc(r['purpose'])} | {r['cost']} | {'yes' if r['id'] in wired else 'preview'} | {esc(r['accessibility'])} |")
    w("")
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}: {len(rows)} recipes, {len(fams)} families, {len(wired)} wired")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
